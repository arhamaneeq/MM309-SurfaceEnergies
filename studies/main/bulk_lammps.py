#!/usr/bin/env python3
"""Generate LAMMPS input decks for finite-temperature bulk equilibration.

Run from the repository root:
    python studies/main/bulk_lammps.py

The generated jobs perform:
  1. a short energy minimization at the trial lattice parameter;
  2. NPT equilibration at 0 bar for 300, 500, or 700 K;
  3. NPT production, recording instantaneous temperature, pressure, volume,
     potential energy, and the equivalent FCC cubic lattice parameter.

The output gives a configuration-specific a(T) estimate. Use the three seeds
for an alloy/temperature to assess variation before choosing a shared a(T).
This script generates jobs only; it does not launch LAMMPS.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path("studies/main")
STRUCTURE_DIR = ROOT / "structures" / "bulk"
RUNS_DIR = ROOT / "runs" / "bulk_equilibration"

LIBRARY_FILE = ROOT / "library.meam"
ALLOY_FILE = ROOT / "FeNiAl.meam"

TEMPERATURES = (300, 500, 700)
TIMESTEP_PS = 0.001  # LAMMPS metal units: timestep is in ps (1 fs)
EQUILIBRATION_STEPS = 5_000
PRODUCTION_STEPS = 10_000
THERMO_EVERY = 100
AVERAGE_EVERY = 10
AVERAGE_REPEATS = 100
AVERAGE_START = AVERAGE_EVERY * AVERAGE_REPEATS
TARGET_PRESSURE_BAR = 0.0
RANDOM_SEED_BASE = 731_000

# ASE/LAMMPS atom type order assumed by the existing project:
# type 1 = Al, type 2 = Fe, type 3 = Ni.
MASS_BY_TYPE = {1: 26.9815, 2: 55.8450, 3: 58.6934}
PAIR_COEFF = "pair_coeff * * library.meam Fe Ni Al FeNiAl.meam Al Fe Ni"


def make_input(temperature: int, seed: int) -> str:
    """Return a LAMMPS input deck for one bulk configuration and temperature."""
    velocity_seed = RANDOM_SEED_BASE + seed % 100_000 + temperature
    return f"""# Generated by studies/main/bulk_lammps.py
clear
units metal
dimension 3
boundary p p p
atom_style atomic
newton on

read_data structure.data
mass 1 {MASS_BY_TYPE[1]}
mass 2 {MASS_BY_TYPE[2]}
mass 3 {MASS_BY_TYPE[3]}

pair_style meam
{PAIR_COEFF}

neighbor 2.0 bin
neigh_modify delay 0 every 1 check yes

thermo {THERMO_EVERY}
thermo_style custom step time temp press pe etotal vol lx ly lz
thermo_modify norm no flush yes

# Remove severe initial overlaps/forces at the trial lattice parameter.
min_style cg
minimize 1.0e-8 1.0e-6 2000 20000

# Heat/equilibrate at the requested temperature and zero external pressure.
# Tdamp=0.1 ps and Pdamp=1.0 ps are initial choices; inspect stability.
timestep {TIMESTEP_PS}
velocity all create {temperature} {velocity_seed} mom yes rot no dist gaussian
fix EQ all npt temp {temperature} {temperature} 0.1 iso {TARGET_PRESSURE_BAR} {TARGET_PRESSURE_BAR} 1.0
run {EQUILIBRATION_STEPS}
unfix EQ

# Production averages. a_fcc is the cubic conventional-cell parameter
# inferred from volume per atom for a 4-atom FCC conventional cell.
variable a_fcc equal (4.0*vol/atoms)^(1.0/3.0)
variable e_atom equal pe/atoms
variable temp_now equal temp
variable press_now equal press
variable volume_now equal vol

fix PROD all npt temp {temperature} {temperature} 0.1 iso {TARGET_PRESSURE_BAR} {TARGET_PRESSURE_BAR} 1.0

fix AVG all ave/time {AVERAGE_EVERY} {AVERAGE_REPEATS} {AVERAGE_START} &
    v_a_fcc v_e_atom v_temp_now v_press_now v_volume_now &
    file bulk_averages.dat
run {PRODUCTION_STEPS}

write_data final.data
write_restart final.restart
unfix AVG
unfix PROD
print "Completed bulk NPT equilibration/production at {temperature} K."
"""


def main() -> None:
    if not STRUCTURE_DIR.is_dir():
        raise FileNotFoundError(
            f"{STRUCTURE_DIR} not found. Run bulk_struct.py first."
        )
    if not LIBRARY_FILE.is_file() or not ALLOY_FILE.is_file():
        raise FileNotFoundError(
            "Expected library.meam and FeNiAl.meam in the repository root."
        )

    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    structures = sorted(STRUCTURE_DIR.glob("*.data"))
    if not structures:
        raise FileNotFoundError(f"No *.data structures found in {STRUCTURE_DIR}")

    manifest: list[dict] = []
    for structure_path in structures:
        if structure_path.name == "manifest.data":
            continue
        metadata_path = structure_path.with_suffix(".json")
        metadata = json.loads(metadata_path.read_text()) if metadata_path.exists() else {}
        seed = int(metadata.get("seed", 0))
        alloy = metadata.get("alloy", structure_path.stem.split("_seed")[0])

        for temperature in TEMPERATURES:
            run_name = f"{alloy}_seed{seed}_T{temperature}"
            run_dir = RUNS_DIR / run_name
            run_dir.mkdir(parents=True, exist_ok=True)

            shutil.copy2(structure_path, run_dir / "structure.data")
            shutil.copy2(LIBRARY_FILE, run_dir / LIBRARY_FILE.name)
            shutil.copy2(ALLOY_FILE, run_dir / ALLOY_FILE.name)
            if metadata_path.exists():
                shutil.copy2(metadata_path, run_dir / "structure.json")

            input_path = run_dir / "in.lammps"
            input_path.write_text(make_input(temperature, seed))
            manifest.append({
                "run": run_name,
                "alloy": alloy,
                "seed": seed,
                "temperature_K": temperature,
                "directory": str(run_dir),
                "input": str(input_path),
            })
            print(f"Wrote {input_path}")

    (RUNS_DIR / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"\nGenerated {len(manifest)} bulk equilibration jobs.")
    print(f"Run directory: {RUNS_DIR}")
    print("These are input decks only; execute them with your LAMMPS runner.")


if __name__ == "__main__":
    main()
