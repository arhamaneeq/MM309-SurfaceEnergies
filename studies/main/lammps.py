
#!/usr/bin/env python3
"""Generate LAMMPS inputs for the MM309 surface-energy study."""

import csv
import json
import shutil
from pathlib import Path

MAIN_DIR = Path(__file__).resolve().parent
STRUCTURE_DIRS = {
    "bulk": MAIN_DIR / "structures" / "bulk",
    "slab": MAIN_DIR / "structures" / "slabs",
}
RUNS_DIR = MAIN_DIR / "runs"

LIBRARY_FILE = MAIN_DIR / "library.meam"
ALLOY_FILE = MAIN_DIR / "FeNiAl.meam"

# ASE's default alphabetical element ordering for these structures.
# Validate this against the structure-generation code before running.
TYPE_TO_ELEMENT = {
    1: "Al",
    2: "Fe",
    3: "Ni",
}

MASSES = {
    "Al": 26.9815,
    "Fe": 55.8450,
    "Ni": 58.6934,
}

# The library extraction order must agree with the indices in FeNiAl.meam.
MEAM_LIBRARY_ORDER = ("Fe", "Ni", "Al")

MINIMIZE_ETOL = 1.0e-10
MINIMIZE_FTOL = 1.0e-10
MINIMIZE_MAXITER = 10_000
MINIMIZE_MAXEVAL = 100_000


def make_input(structure_type: str) -> str:
    """Build a fixed-cell atomic relaxation input."""
    if structure_type == "bulk":
        boundary = "p p p"
    elif structure_type == "slab":
        boundary = "p p f"
    else:
        raise ValueError(f"Unknown structure type: {structure_type}")

    mass_commands = "\n".join(
        f"mass {atom_type} {MASSES[element]}"
        for atom_type, element in TYPE_TO_ELEMENT.items()
    )

    library_elements = " ".join(MEAM_LIBRARY_ORDER)
    type_mapping = " ".join(
        TYPE_TO_ELEMENT[i] for i in sorted(TYPE_TO_ELEMENT)
    )

    return f"""# Generated by generate_lammps_inputs.py
# Structure type: {structure_type}
# Fixed-cell atomic relaxation

clear
units           metal
dimension       3
boundary        {boundary}
atom_style      atomic
newton          on

read_data       structure.data

{mass_commands}

pair_style      meam
pair_coeff      * * library.meam Fe Ni Al FeNiAl.meam Al Fe Ni

neighbor        2.0 bin
neigh_modify    delay 0 every 1 check yes

thermo          100
thermo_style    custom step atoms pe etotal lx ly lz
thermo_modify   norm no

run             0
variable        E_initial equal pe
print           "INITIAL_PE = ${{E_initial}}" file energy.txt screen yes

min_style       cg
minimize        1.0e-10 1.0e-10 10000 100000

variable        E_final equal pe
variable        N equal atoms
print           "FINAL_PE = ${{E_final}}" append energy.txt screen yes
print           "N_ATOMS = ${{N}}" append energy.txt screen yes

write_data      relaxed.data
write_restart   relaxed.restart

print           "Completed {structure_type} relaxation."
"""


def generate_run(data_path: Path, structure_type: str) -> dict:
    """Create one run directory and its input/supporting files."""
    run_dir = RUNS_DIR / data_path.stem
    run_dir.mkdir(parents=True, exist_ok=True)

    shutil.copy2(data_path, run_dir / "structure.data")

    # Copy metadata when available.
    metadata_path = data_path.with_suffix(".json")
    metadata = {}
    if metadata_path.exists():
        shutil.copy2(metadata_path, run_dir / "structure.json")
        metadata = json.loads(metadata_path.read_text())

    # Self-contained potential files make runs portable.
    shutil.copy2(LIBRARY_FILE, run_dir / LIBRARY_FILE.name)
    shutil.copy2(ALLOY_FILE, run_dir / ALLOY_FILE.name)

    (run_dir / "in.lammps").write_text(make_input(structure_type))

    return {
        "run_name": data_path.stem,
        "structure_type": structure_type,
        "structure_file": str(data_path.relative_to(MAIN_DIR)),
        "run_directory": str(run_dir.relative_to(MAIN_DIR)),
        "configuration": metadata.get("configuration", data_path.stem),
        "random_seed": metadata.get("random_seed", ""),
        "composition_target": json.dumps(
            metadata.get("composition_target", {}),
            sort_keys=True,
        ),
        "miller_indices": (
            data_path.stem.rsplit("_", 1)[-1]
            if structure_type == "slab"
            else ""
        ),
    }


def main() -> None:
    if not LIBRARY_FILE.is_file():
        raise FileNotFoundError(f"Missing MEAM library: {LIBRARY_FILE}")
    if not ALLOY_FILE.is_file():
        raise FileNotFoundError(f"Missing MEAM parameters: {ALLOY_FILE}")

    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    manifest = []

    for structure_type, directory in STRUCTURE_DIRS.items():
        data_files = sorted(directory.glob("*.data"))
        if not data_files:
            raise FileNotFoundError(
                f"No .data structures found in {directory}"
            )

        for data_path in data_files:
            manifest.append(generate_run(data_path, structure_type))

    manifest_path = RUNS_DIR / "manifest.csv"
    with manifest_path.open("w", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=manifest[0].keys())
        writer.writeheader()
        writer.writerows(manifest)

    print(f"Generated {len(manifest)} LAMMPS inputs.")
    print(f"Bulk runs: {sum(r['structure_type'] == 'bulk' for r in manifest)}")
    print(f"Slab runs: {sum(r['structure_type'] == 'slab' for r in manifest)}")
    print(f"Manifest: {manifest_path}")


if __name__ == "__main__":
    main()
